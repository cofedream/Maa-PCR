"""Generate or check the compiled GUI and Python pins for the reviewed calibration index."""
import argparse
import hashlib
from pathlib import Path
import sys
from tempfile import NamedTemporaryFile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
from pcr_maa.clan_battle_calibration_data import INDEX_PATH, _path, parse_index, read_profile, resolve_profile_files

PYTHON_PIN = 'src/pcr_maa/_clan_calibration_pin.py'
GUI_PIN = 'gui/MFAAvalonia/MFAAvalonia/Pcr/PcrClanCalibrationPin.g.cs'


def generated_sources(digest):
    return {
        PYTHON_PIN: ('# Generated by scripts/sync_clan_calibration_index.py\n'
                     f"INDEX_SHA256 = '{digest}'\n").encode('ascii'),
        GUI_PIN: ('// Generated by scripts/sync_clan_calibration_index.py\n'
                  'namespace MFAAvalonia.Pcr;\n\n'
                  'internal static class PcrClanCalibrationPin\n'
                  '{\n'
                  f'    internal const string IndexSha256 = "{digest}";\n'
                  '}\n').encode('ascii'),
    }


def verified_index(root):
    root = Path(root).resolve()
    index = _path(root, INDEX_PATH)
    if not index.is_file() or not 0 < index.stat().st_size <= 1024 * 1024:
        raise ValueError('clan_battle_calibration_index_missing_or_invalid_size')
    data = index.read_bytes()
    manifest = parse_index(root, data)
    for entry in manifest['entries']:
        profile = read_profile(root, entry)
        capabilities = entry.get('capabilities', ['simulation'])
        if profile['version'] == 1 and set(capabilities) - {'simulation'}:
            raise ValueError('clan_battle_calibration_legacy_capability_invalid')
        resolve_profile_files(root, profile, capabilities)
    return data


def sync(root, *, write=False):
    root = Path(root).resolve()
    data = verified_index(root)
    digest = hashlib.sha256(data).hexdigest()
    outputs = generated_sources(digest)
    pending = {}
    for relative, content in outputs.items():
        path = _path(root, relative)
        if not path.is_file() or path.read_bytes() != content:
            pending[path] = content
    if pending and not write:
        names = ', '.join(path.relative_to(root).as_posix() for path in pending)
        raise ValueError(f'calibration pins out of date: {names}; run scripts/sync_clan_calibration_index.py --write')
    # Stage both files before publishing either one. Interrupted runs are safe to repeat.
    staged = {}
    try:
        for path, content in pending.items():
            with NamedTemporaryFile(dir=path.parent, prefix=path.name + '.', suffix='.tmp', delete=False) as stream:
                staged[path] = Path(stream.name)
                stream.write(content)
        if (root / INDEX_PATH).read_bytes() != data:
            raise ValueError('calibration index changed during generation')
        for path, temporary in staged.items():
            temporary.replace(path)
    finally:
        for temporary in staged.values():
            temporary.unlink(missing_ok=True)
    return digest


def check_packaged_index(player, gui_source, digest):
    """Check the data and both generated sources actually used to assemble the release."""
    if hashlib.sha256(verified_index(player)).hexdigest() != digest:
        raise ValueError('packaged calibration index differs from build preflight')
    for relative, content in generated_sources(digest).items():
        root = gui_source if relative == GUI_PIN else player
        if _path(root, relative).read_bytes() != content:
            raise ValueError('packaged calibration pin differs from build preflight: ' + relative)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument('--root', type=Path, default=ROOT, help='source or isolated staging checkout')
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument('--check', action='store_true', help='report stale generated sources (default)')
    modes.add_argument('--write', action='store_true', help='generate pins from the reviewed index')
    args = parser.parse_args(argv)
    try:
        print(sync(args.root, write=args.write))
    except (OSError, ValueError) as exc:
        parser.exit(1, f'{exc}\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
