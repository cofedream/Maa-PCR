import argparse
import hashlib
import json
import math
from pathlib import Path
import struct
import wave


AUTHOR = "pcr-agent-maa contributors (Codex-assisted original geometry and synthesis)"
DATE = "2026-10-03"
LICENSE = "MIT"
GUI = "gui/MFAAvalonia"
BMP = f"{GUI}/Markdown.Avalonia.Tight/Assets/ImageNotFound.bmp"
WAV = f"{GUI}/MFAAvalonia/Assets/Sound/SystemNotification.wav"


def make_placeholder():
    width, height = 32, 24
    stride = (width * 3 + 3) & ~3
    pixels = bytearray()
    for y in reversed(range(height)):
        line = bytearray()
        for x in range(width):
            border = x in (1, width - 2) and 1 <= y <= height - 2
            border |= y in (1, height - 2) and 1 <= x <= width - 2
            cross = 9 <= x <= 22 and (abs((x - 9) - (y - 5)) <= 1
                                     or abs((22 - x) - (y - 5)) <= 1)
            r, g, b = (94, 112, 118) if border or cross else (238, 243, 243)
            line.extend((b, g, r))
        pixels.extend(line + bytes(stride - len(line)))
    offset = 14 + 40
    return (struct.pack('<2sIHHI', b'BM', offset + len(pixels), 0, 0, offset)
            + struct.pack('<IiiHHIIiiII', 40, width, height, 1, 24, 0,
                          len(pixels), 3780, 3780, 0, 0) + pixels)


def make_chime(path):
    rate = 22050
    samples = bytearray()
    for frequency, seconds in ((660, 0.18), (0, 0.04), (880, 0.22)):
        count = round(seconds * rate)
        for index in range(count):
            progress = index / max(count - 1, 1)
            envelope = math.sin(math.pi * progress) ** 2
            value = (round(0.12 * 32767 * envelope
                           * math.sin(2 * math.pi * frequency * index / rate))
                     if frequency else 0)
            samples.extend(struct.pack('<h', value))
    with wave.open(str(path), 'wb') as output:
        output.setnchannels(1)
        output.setsampwidth(2)
        output.setframerate(rate)
        output.writeframes(samples)


def generate(root):
    root = Path(root).resolve()
    path = root / BMP
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(make_placeholder())
    make_chime(root / WAV)
    rows = []
    for name, description in (
            (BMP, 'Original geometric missing-image placeholder; 32x24, 24-bit BMP'),
            (WAV, 'Original 660/880 Hz synthesized chime; mono PCM16, 22050 Hz')):
        data = (root / name).read_bytes()
        rows.append(dict(path=name, size=len(data), sha256=hashlib.sha256(data).hexdigest(),
                         description=description, author=AUTHOR, authored_date=DATE,
                         declared_license=LICENSE, license_file='LICENSE',
                         input_assets=[], origin='generated by scripts/generate_gui_release_assets.py'))
    folder = f'{GUI}/SukiUI/Theme/ManagedFileChooser.axaml'
    data = (root / folder).read_bytes()
    geometry = 'M2,5 L10,5 L13,8 L22,8 L22,21 L2,21 Z'
    if geometry.encode('ascii') not in data:
        raise ValueError('Original folder geometry missing from source')
    rows.append(dict(path=folder, size=len(data), sha256=hashlib.sha256(data).hexdigest(),
                     description='Original simple folder PathIcon geometry; 24x24, margin 2',
                     geometry=geometry, author=AUTHOR, authored_date=DATE,
                     declared_license='GPL-3.0', license_file=f'{GUI}/LICENSE',
                     input_assets=[], origin='New source-vector geometry in ManagedFileChooser.axaml'))
    return dict(schema_version=1, purpose='original_gui_assets',
                generator='scripts/generate_gui_release_assets.py',
                generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                existing_assets_read=False, files=rows)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--receipt', type=Path)
    args = parser.parse_args()
    result = generate(args.root)
    if args.receipt:
        args.receipt.parent.mkdir(parents=True, exist_ok=True)
        args.receipt.write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n',
                                encoding='utf-8')
    print(json.dumps(result, ensure_ascii=False))
